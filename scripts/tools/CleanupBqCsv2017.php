namespace oat\taoInvalsi\scripts\tools;

use oat\oatbox\action\Action;
use \common_report_Report as Report;

/**
 * INV-BQ 2017 Results Export Mitigation Script
 * 
 * This script at cleaning results export for INV-BQ 2017. The resulting CSV
 * files will be written in the folder where the source CSV file is located.
 * 
 * WARNING: This script considers that the input CSV file has its first
 * row dedicated to contain column names!
 * 
 * Parameters:
 * 
 * Parameter 1: The path to the source CSV file.
 * Parameter 2: Optional parameter to set the consistency threshold. Default value is 13.
 * Parameter 3: (integer 0|1) Optional parameter to set whether or not output additional information about duplicate resolution.
 * Parameter 4: Optional parameter to set the file prefix to be applied on files generated by the script.
 */
class CleanupBqCsv2017 implements Action
{
    public function __invoke($params)
    {
        if (!empty($params[0])) {
            $source = $params[0];
        } else {
            return new Report(
                Report::TYPE_ERROR,
                "'Source Parameter' not provided."
            );
        }
        
        $source = $params[0];
        
        $consistencyThreshold = 13;
        if (isset($params[1])) {
            $consistencyThreshold = intval($params[1]);
        }
        
        $verbose = false;
        if (isset($params[2])) {
            $verbose = boolval($params[2]);
        }
        
        $filePrefix = '';
        if (isset($params[3])) {
            $filePrefix = $params[3];
        }
        
        $realSource = realpath($source);
        
        if ($realSource === false) {
            return new Report(
                Report::TYPE_ERROR,
                "'Source Parameter' value '${source}' could not be resolved on the file system."
            );
        }
        
        $pathInfo = pathinfo($realSource);
        $basePath = $pathInfo['dirname'];
        
        $report = new Report(
            Report::TYPE_INFO,
            'BQ 2017 CSV Clean up Script Report'
        );
        
        $scripts = [
            'branch'    => new \oat\taoInvalsi\scripts\tools\ResolveBranchRuleFromBqCsv(),
            'clean'   => new \oat\tao\scripts\tools\RemoveCsvRowsByPattern(),
            'dupes'   => new \oat\tao\scripts\tools\ExtractCsvDuplicates(),
            'exclude'   => new \oat\tao\scripts\tools\CsvExclusion(),
            'resolve' => new \oat\taoInvalsi\scripts\tools\ResolveBqCsvDuplicates(),
            'merge' => new \oat\tao\scripts\tools\MergeCsv()
        ];
        
        $report->add(
            $scripts['branch']([
                $realSource,
                $basePath . "/${filePrefix}aggregate-br.csv",
                0,
                1
            ])
        );
        
        $report->add(
            $scripts['clean']([
                $basePath . "/${filePrefix}aggregate-br.csv",
                $basePath . "/${filePrefix}aggregate-noqa.csv",
                0,
                "/^Test-taker|^OAT_QA/u",
                1
            ])
        );
        
        $report->add(
            $scripts['dupes']([
                $basePath . "/${filePrefix}aggregate-noqa.csv",
                $basePath . "/${filePrefix}duplicates.csv",
                0,
                1
            ])
        );
        
        $report->add(
            $scripts['exclude']([
                $basePath . "/${filePrefix}aggregate-noqa.csv",
                $basePath . "/${filePrefix}aggregate-noqa-noduplicates.csv",
                0,
                1,
                $basePath . "/${filePrefix}duplicates.csv"
            ])
        );
        
        $report->add(
            $scripts['resolve']([
                $basePath . "/${filePrefix}duplicates.csv",
                $basePath . "/${filePrefix}resolved-duplicates.csv",
                0,
                1,
                $consistencyThreshold,
                $verbose
            ])
        );
        
        $report->add(
            $scripts['exclude']([
                $basePath . "/${filePrefix}duplicates.csv",
                $basePath . "/${filePrefix}remaining-duplicates.csv",
                0,
                1,
                $basePath . "/${filePrefix}resolved-duplicates.csv"
            ])
        );
        
        $report->add(
            $scripts['merge']([
                $basePath . "/${filePrefix}aggregate-noqa-noduplicates.csv",
                $basePath . "/${filePrefix}resolved-duplicates.csv",
                $basePath . "/${filePrefix}aggregate-resolved.csv",
                1
            ])
        );
        
        return $report;
    }
}
