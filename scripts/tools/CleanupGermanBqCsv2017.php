namespace oat\taoInvalsi\scripts\tools;

use oat\oatbox\action\Action;
use \common_report_Report as Report;

/**
 * INV-BQ 2017 Results Export Mitigation Script
 * 
 * This script at cleaning results export for GERMAN-BQ 2017. The resulting CSV
 * files will be written in the folder where the source CSV file is located.
 * 
 * WARNING: This script considers that the input CSV file has its first
 * row dedicated to contain column names!
 * 
 * Parameters:
 * 
 * Parameter 1: The path to the source CSV file.
 * Parameter 2: Optional parameter to set the file prefix to be applied on files generated by the script.
 */
class CleanupGermanBqCsv2017 implements Action
{
    public function __invoke($params)
    {
        if (!empty($params[0])) {
            $source = $params[0];
        } else {
            return new Report(
                Report::TYPE_ERROR,
                "'Source Parameter' not provided."
            );
        }
        
        $source = $params[0];
        
        $filePrefix = '';
        if (isset($params[1])) {
            $filePrefix = $params[1];
        }
        
        $realSource = realpath($source);
        
        if ($realSource === false) {
            return new Report(
                Report::TYPE_ERROR,
                "'Source Parameter' value '${source}' could not be resolved on the file system."
            );
        }
        
        $pathInfo = pathinfo($realSource);
        $basePath = $pathInfo['dirname'];
        
        $report = new Report(
            Report::TYPE_INFO,
            'GERMAN-BQ 2017 CSV Clean up Script Report'
        );
        
        $scripts = [
            'branch'   => new \oat\taoInvalsi\scripts\tools\ResolveBranchRuleFromGermanBq2017Csv(),
            'columns'  => new \oat\taoInvalsi\scripts\tools\RemoveExtraColumnsFromGermanBq2017Csv(),
            'dupes'   => new \oat\tao\scripts\tools\ExtractCsvDuplicates(),
        ];
        
        $report->add(
            $scripts['branch']([
                $realSource,
                $basePath . "/${filePrefix}br-invalidated.csv",
                1
            ])
        );
        
        $report->add(
            $scripts['columns']([
                $basePath . "/${filePrefix}br-invalidated.csv",
                $basePath . "/${filePrefix}extracolumns-removed.csv"
            ])
        );
        
        $report->add(
            $scripts['dupes']([
                $basePath . "/${filePrefix}extracolumns-removed.csv",
                $basePath . "/${filePrefix}duplicates.csv",
                0,
                1
            ])
        );
        
        return $report;
    }
}
